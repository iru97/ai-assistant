#!/usr/bin/env node

/**
 * Generate SQL seed script from JSON data files
 *
 * This script reads prompts.json and affirmations.json and generates
 * a SQL migration file with INSERT statements for seeding the database.
 *
 * Usage:
 *   node scripts/generate-seed-sql.js
 *   npm run seed:generate
 *
 * Output:
 *   supabase/migrations/003_seed_data.sql
 */

const fs = require('fs');
const path = require('path');

// File paths
const PROMPTS_JSON = path.join(__dirname, '../content/prompts.json');
const AFFIRMATIONS_JSON = path.join(__dirname, '../content/affirmations.json');
const OUTPUT_SQL = path.join(__dirname, '../supabase/migrations/004_seed_data.sql');

/**
 * Escape single quotes for SQL
 * Example: "What's" -> "What''s"
 */
function escapeSql(text) {
  if (!text) return '';
  return text.replace(/'/g, "''");
}

/**
 * Generate SQL INSERT statement for prompts
 */
function generatePromptsInsert(prompts) {
  const values = prompts.map(prompt => {
    const category = escapeSql(prompt.category);
    const text = escapeSql(prompt.text_en); // Using English text only for now
    return `  ('${category}', '${text}')`;
  });

  return `-- ============================================================================
-- Insert prompts (${prompts.length} total)
-- ============================================================================
INSERT INTO prompts (category, prompt_text)
SELECT * FROM (VALUES
${values.join(',\n')}
) AS v(category, prompt_text)
WHERE NOT EXISTS (SELECT 1 FROM prompts LIMIT 1);
`;
}

/**
 * Generate SQL INSERT statement for affirmations
 */
function generateAffirmationsInsert(affirmations) {
  const values = affirmations.map(affirmation => {
    // Map 'theme' from JSON to 'category' in DB
    const category = escapeSql(affirmation.theme);
    const text = escapeSql(affirmation.text_en); // Using English text only for now
    return `  ('${category}', '${text}')`;
  });

  return `-- ============================================================================
-- Insert affirmations (${affirmations.length} total)
-- ============================================================================
INSERT INTO affirmations (category, affirmation_text)
SELECT * FROM (VALUES
${values.join(',\n')}
) AS v(category, affirmation_text)
WHERE NOT EXISTS (SELECT 1 FROM affirmations LIMIT 1);
`;
}

/**
 * Main function
 */
function main() {
  console.log('🔄 Generating SQL seed script from JSON files...\n');

  // Read JSON files
  console.log(`📖 Reading ${PROMPTS_JSON}`);
  const promptsData = JSON.parse(fs.readFileSync(PROMPTS_JSON, 'utf8'));
  const prompts = promptsData.prompts;
  console.log(`   ✓ Found ${prompts.length} prompts\n`);

  console.log(`📖 Reading ${AFFIRMATIONS_JSON}`);
  const affirmationsData = JSON.parse(fs.readFileSync(AFFIRMATIONS_JSON, 'utf8'));
  const affirmations = affirmationsData.affirmations;
  console.log(`   ✓ Found ${affirmations.length} affirmations\n`);

  // Generate SQL
  console.log('🔨 Generating SQL statements...');
  const promptsSql = generatePromptsInsert(prompts);
  const affirmationsSql = generateAffirmationsInsert(affirmations);

  // Build complete SQL file
  const completeSql = `-- ============================================================================
-- Journal Safe MVP - Seed Data Migration
-- ============================================================================
-- This migration populates the prompts and affirmations tables with
-- content for the eating disorder-safe wellness journaling app.
--
-- Data sources:
--   - content/prompts.json (100 journaling prompts)
--   - content/affirmations.json (50 affirmations)
--
-- Generated by: scripts/generate-seed-sql.js
-- Generated at: ${new Date().toISOString()}
--
-- Note: This migration is idempotent - it will only insert data if the
-- tables are empty, so it's safe to run multiple times.
-- ============================================================================

${promptsSql}
${affirmationsSql}
-- ============================================================================
-- Migration Complete
-- ============================================================================
-- Summary:
--   - ${prompts.length} prompts inserted
--   - ${affirmations.length} affirmations inserted
--
-- Next steps:
--   1. Run: supabase db push
--   2. Verify data in Supabase Studio
--   3. Test prompt/affirmation fetching in app
-- ============================================================================
`;

  // Write to file
  console.log(`\n💾 Writing to ${OUTPUT_SQL}`);
  fs.writeFileSync(OUTPUT_SQL, completeSql, 'utf8');
  console.log('   ✓ File written successfully\n');

  // Summary
  console.log('✨ Summary:');
  console.log(`   - ${prompts.length} prompts`);
  console.log(`   - ${affirmations.length} affirmations`);
  console.log(`   - Output: ${OUTPUT_SQL}`);
  console.log('\n✅ Done! Run "supabase db push" to apply the migration.\n');
}

// Run the script
main();
